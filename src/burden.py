"""Burden Index B_i — five-component construct anchored to literature.

Components (each computed at tract level, normalized to [0,1] across the metro):
  Noise        — day-night average sound energy from vertiport operations at
                 each tract centroid, from the take-off/landing level measured
                 for the Joby aircraft (Pascioni et al. 2022); additive across
                 vertiports.
  Visual       — line-of-sight + approach/departure cone overlap with tract;
                 proxied by inverse distance to nearest vertiport in 1500m buffer.
  Traffic      — incremental TNC ground access generated by vertiport demand;
                 proxied by gravity-weighted access trip generation per tract.
  LandUse      — sensitive-receiver overlay penalty (schools/hospitals/parks
                 within buffer of any vertiport).
  SafetyRisk   — distance-decayed exposure to overflight corridors between vertiports.

Validation:
    Spatial correlation of B against CalEnviroScreen 4.0 Pollution Burden percentile
    is reported as a construct-validity diagnostic.
"""

from __future__ import annotations
import numpy as np
import pandas as pd
import geopandas as gpd
from scipy.stats import spearmanr

from .config import CFG, BurdenParams
from .data_layer import load_tracts_joined
from .candidates import _to_metric, _metric_crs_for
from .accessibility import euclid_dist_m


# ----------------------------------------------------------------------------
# Component 1 — Noise
# ----------------------------------------------------------------------------
def event_sel_dba(d_m: np.ndarray, params: BurdenParams) -> np.ndarray:
    """Sound exposure level of one take-off or landing at distance d.

    L_Amax falls by spherical spreading (-20 log10 d) and atmospheric
    absorption. The effective duration of the event grows in proportion to d
    until it reaches the length of the take-off or landing phase, and
    SEL = L_Amax + 10 log10(duration).
    """
    d = np.maximum(d_m, params.noise_near_field_m)
    la_max = (params.la_max_takeoff_100m_dba - 20.0 * np.log10(d / 100.0)
              - params.atmospheric_absorption_db_per_km * (d - 100.0) / 1000.0)
    duration = np.minimum(params.event_duration_100m_s * d / 100.0, params.event_duration_max_s)
    return la_max + 10.0 * np.log10(duration)


def vertiport_dnl_dba(d_m: np.ndarray, ops_per_day: float, params: BurdenParams) -> np.ndarray:
    """Day-night average sound level at distance d from one vertiport."""
    weighted_ops = ops_per_day * (1.0 + 9.0 * params.night_ops_share)
    return event_sel_dba(d_m, params) + 10.0 * np.log10(max(weighted_ops, 1e-9)) - 10.0 * np.log10(86400.0)


def tract_vertiport_distance_m(tracts: gpd.GeoDataFrame, candidates: gpd.GeoDataFrame,
                               selected_idx: np.ndarray, metro: str) -> np.ndarray:
    epsg_m = _metric_crs_for(metro)
    t_xy = np.array([(g.x, g.y) for g in _to_metric(tracts, epsg_m).geometry.centroid])
    s_xy = np.array([(g.x, g.y) for g in _to_metric(candidates.iloc[selected_idx], epsg_m).geometry])
    return euclid_dist_m(t_xy, s_xy)


def noise_exposure_per_tract(tracts: gpd.GeoDataFrame,
                              candidates: gpd.GeoDataFrame,
                              selected_idx: np.ndarray,
                              ops_per_day: float,
                              params: BurdenParams,
                              metro: str) -> np.ndarray:
    """Day-night average sound energy at each tract centroid, summed over vertiports.

    Energy (10^(DNL/10)) is additive across sources, so the exposure from a
    network is the sum of the exposures from its vertiports.
    """
    if len(selected_idx) == 0:
        return np.zeros(len(tracts))
    d_m = tract_vertiport_distance_m(tracts, candidates, selected_idx, metro)
    return (10.0 ** (vertiport_dnl_dba(d_m, ops_per_day, params) / 10.0)).sum(axis=1)


def network_dnl_dba(tracts: gpd.GeoDataFrame, candidates: gpd.GeoDataFrame,
                    selected_idx: np.ndarray, ops_per_day: float,
                    params: BurdenParams, metro: str) -> np.ndarray:
    """Day-night average sound level at each tract centroid from a vertiport network."""
    energy = noise_exposure_per_tract(tracts, candidates, selected_idx, ops_per_day, params, metro)
    return 10.0 * np.log10(np.maximum(energy, 1e-12))


# ----------------------------------------------------------------------------
# Component 2 — Visual
# ----------------------------------------------------------------------------
def visual_burden(tracts: gpd.GeoDataFrame,
                   candidates: gpd.GeoDataFrame,
                   selected_idx: np.ndarray,
                   metro: str,
                   buffer_m: float = 1500.0) -> np.ndarray:
    if len(selected_idx) == 0:
        return np.zeros(len(tracts))
    epsg_m = _metric_crs_for(metro)
    tracts_m = _to_metric(tracts, epsg_m)
    sel_m = _to_metric(candidates.iloc[selected_idx], epsg_m)
    t_xy = np.array([(g.x, g.y) for g in tracts_m.geometry.centroid])
    s_xy = np.array([(g.x, g.y) for g in sel_m.geometry])
    d_m = euclid_dist_m(t_xy, s_xy)
    d_m_min = d_m.min(axis=1)
    # Inverse-distance kernel within buffer
    raw = np.where(d_m_min > buffer_m, 0.0, (buffer_m - d_m_min) / buffer_m)
    return raw  # already in [0,1]


# ----------------------------------------------------------------------------
# Component 3 — Traffic (induced ground access)
# ----------------------------------------------------------------------------
def traffic_burden(tracts: gpd.GeoDataFrame,
                    candidates: gpd.GeoDataFrame,
                    selected_idx: np.ndarray,
                    metro: str,
                    catchment_m: float = 3000.0) -> np.ndarray:
    """Tract burden = total population within catchment of each vertiport, allocated
    to the tract by inverse distance. Higher = more induced TNC traffic."""
    if len(selected_idx) == 0:
        return np.zeros(len(tracts))
    epsg_m = _metric_crs_for(metro)
    tracts_m = _to_metric(tracts, epsg_m)
    sel_m = _to_metric(candidates.iloc[selected_idx], epsg_m)
    t_xy = np.array([(g.x, g.y) for g in tracts_m.geometry.centroid])
    s_xy = np.array([(g.x, g.y) for g in sel_m.geometry])
    d_m = euclid_dist_m(t_xy, s_xy)
    inside = d_m <= catchment_m
    weight = np.where(inside, 1.0 - d_m / catchment_m, 0.0)
    return weight.sum(axis=1)


# ----------------------------------------------------------------------------
# Component 4 — LandUse (sensitive-receiver penalty)
# ----------------------------------------------------------------------------
def landuse_burden(tracts: gpd.GeoDataFrame,
                    candidates: gpd.GeoDataFrame,
                    selected_idx: np.ndarray,
                    metro: str,
                    sensitive_buffer_m: float = 800.0) -> np.ndarray:
    """Tracts with high renter share + high pop density inside vertiport buffer
    accrue land-use burden (proxy for displacement / use-conflict)."""
    if len(selected_idx) == 0:
        return np.zeros(len(tracts))
    epsg_m = _metric_crs_for(metro)
    tracts_m = _to_metric(tracts, epsg_m)
    sel_m = _to_metric(candidates.iloc[selected_idx], epsg_m)
    t_xy = np.array([(g.x, g.y) for g in tracts_m.geometry.centroid])
    s_xy = np.array([(g.x, g.y) for g in sel_m.geometry])
    d_m = euclid_dist_m(t_xy, s_xy)
    nearest = d_m.min(axis=1)
    proximity = np.where(nearest > sensitive_buffer_m, 0.0,
                         (sensitive_buffer_m - nearest) / sensitive_buffer_m)
    pct_renter = tracts["pct_renter"].fillna(0.0).values
    pop_density = tracts["pop"].fillna(0.0).values / np.maximum(tracts["land_area_m2"].values, 1.0) * 1e6
    pop_density_norm = pop_density / np.nanpercentile(pop_density, 95)
    return proximity * (0.5 + 0.5 * pct_renter) * np.minimum(pop_density_norm, 2.0)


# ----------------------------------------------------------------------------
# Component 5 — Safety risk (overflight corridor exposure)
# ----------------------------------------------------------------------------
def safety_burden(tracts: gpd.GeoDataFrame,
                   candidates: gpd.GeoDataFrame,
                   selected_idx: np.ndarray,
                   metro: str) -> np.ndarray:
    """Distance from tract centroid to nearest straight-line corridor between any pair
    of selected vertiports. Closer = higher risk perception."""
    if len(selected_idx) < 2:
        return np.zeros(len(tracts))
    epsg_m = _metric_crs_for(metro)
    tracts_m = _to_metric(tracts, epsg_m)
    sel_m = _to_metric(candidates.iloc[selected_idx], epsg_m)
    t_xy = np.array([(g.x, g.y) for g in tracts_m.geometry.centroid])
    s_xy = np.array([(g.x, g.y) for g in sel_m.geometry])

    n = len(t_xy)
    nearest = np.full(n, np.inf)
    # Iterate vertiport pairs (vectorized point-to-segment distance)
    for ki in range(len(s_xy)):
        for kj in range(ki + 1, len(s_xy)):
            a, b = s_xy[ki], s_xy[kj]
            ab = b - a
            ab_len2 = (ab * ab).sum()
            if ab_len2 < 1e-6:
                continue
            t = ((t_xy - a) @ ab) / ab_len2
            t = np.clip(t, 0.0, 1.0)
            proj = a + t[:, None] * ab
            d = np.sqrt(((t_xy - proj) ** 2).sum(axis=1))
            nearest = np.minimum(nearest, d)
    # Convert to [0,1]: closer than 500m = max risk; >5km = 0
    risk = np.clip(1.0 - nearest / 5000.0, 0.0, 1.0)
    risk = np.where(nearest > 5000.0, 0.0, risk)
    return risk


