# Assembly
# ----------------------------------------------------------------------------
def _normalize(x: np.ndarray) -> np.ndarray:
    p99 = np.nanpercentile(x[x > 0], 99) if np.any(x > 0) else 1.0
    return np.clip(x / max(p99, 1e-9), 0.0, 1.0)


def compute_burden_index(metro: str,
                          candidates: gpd.GeoDataFrame,
                          selected_idx: np.ndarray,
                          ops_per_day_per_vertiport: float = 80.0,
                          params: BurdenParams | None = None) -> pd.DataFrame:
    """Aggregate B_i = w1·N + w2·V + w3·T + w4·L + w5·S."""
    params = params or CFG.burden
    tracts = load_tracts_joined(metro)

    noise = noise_exposure_per_tract(tracts, candidates, selected_idx,
                                      ops_per_day_per_vertiport, params, metro)
    visual = visual_burden(tracts, candidates, selected_idx, metro)
    traffic = traffic_burden(tracts, candidates, selected_idx, metro)
    landuse = landuse_burden(tracts, candidates, selected_idx, metro)
    safety = safety_burden(tracts, candidates, selected_idx, metro)

    components = pd.DataFrame({
        "tract_geoid": tracts["tract_geoid"].values,
        "noise":   _normalize(noise),
        "visual":  _normalize(visual),
        "traffic": _normalize(traffic),
        "landuse": _normalize(landuse),
        "safety":  _normalize(safety),
    })
    components["B_raw"] = (
        params.w_noise * components["noise"] +
        params.w_visual * components["visual"] +
        params.w_traffic * components["traffic"] +
        params.w_landuse * components["landuse"] +
        params.w_safety * components["safety"]
    )

    components["B"] = components["B_raw"]
    return components


def burden_validation_against_ces(B_i: pd.DataFrame, metro: str = "la") -> dict:
    """Spearman correlation between B and CES Pollution Burden percentile (construct validity).

    We only require non-null `pollution_burden_pctl` (the multiplicative-input column);
    ces_pctl can be missing in some CES releases without invalidating the test.
    """
    tracts = load_tracts_joined(metro)
    if "pollution_burden_pctl" not in tracts.columns:
        return {"available": False, "reason": "CES not loaded"}
    join = B_i.merge(tracts[["tract_geoid", "pollution_burden_pctl", "ces_pctl"]],
                     on="tract_geoid", how="inner").dropna(subset=["pollution_burden_pctl"])
    # Restrict to tracts with B > 0 (meaningful burden); flat zeros aren't informative
    join = join[join["B"] > 0]
    if len(join) < 50:
        return {"available": False, "reason": f"only {len(join)} tracts with both B>0 and CES"}
    rho_pb, p_pb = spearmanr(join["B"], join["pollution_burden_pctl"])
    out = {
        "available": True,
        "n": int(len(join)),
        "spearman_vs_pollution_burden": float(rho_pb),
        "p_vs_pollution_burden": float(p_pb),
    }
    ces_join = join.dropna(subset=["ces_pctl"])
    if len(ces_join) >= 50:
        rho_ces, p_ces = spearmanr(ces_join["B"], ces_join["ces_pctl"])
        out["spearman_vs_ces"] = float(rho_ces)
        out["p_vs_ces"] = float(p_ces)
    return out
